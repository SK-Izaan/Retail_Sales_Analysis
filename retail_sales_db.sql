CREATE DATABASE retail_sales;
USE retail_sales;
CREATE TABLE sales (
    transaction_id INT,date DATE,
    customer_id VARCHAR(20),
    gender VARCHAR(10),
    age INT,
    product_category VARCHAR(50),
    quantity INT,
    price_per_unit DECIMAL(10,2),
    total_amount DECIMAL(10,2)
);
-- Q1 Find the total revenue generated from all transactions. 
select sum(total_amount) as total_revenue
from sales;

-- Q2 Find the total number of transactions in the sales table.
select count(transaction_id) as total_transactions
from sales;

-- Q3 Find the average amount spent per transaction.
select avg(total_amount) as avg_transaction_value
from sales;

