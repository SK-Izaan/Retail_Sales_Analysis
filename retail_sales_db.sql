-- Q39 Find the product category that generated the highest total revenue in each year.
WITH revenue AS (
    SELECT YEAR(date) AS year, product_category, SUM(total_amount) AS total_revenue
    FROM sales
    GROUP BY YEAR(date), product_category
),
ranked AS (
    SELECT year, product_category, total_revenue,
	ROW_NUMBER() OVER (PARTITION BY year ORDER BY total_revenue DESC) AS rn
    FROM revenue
)
SELECT year, product_category, total_revenue
FROM ranked
WHERE rn = 1;

-- Q40 Find all customers and rank them based on their total spending.
with total_spending as (
select customer_id, sum(total_amount) as total_spending
from sales
group by customer_id),
ranked as (
select customer_id, total_spending,
row_number() over (order by total_spending desc) as customer_rank
from total_spending
)
select customer_id, total_spending, customer_rank
from ranked;